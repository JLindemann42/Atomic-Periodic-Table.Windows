// Emits Atomic.Core/Text/UnicodeScripts.g.cs from the JDK's own Unicode tables.
//
// .NET has no equivalent of java.lang.Character.UnicodeScript, and the engine's Tokenizer
// depends on it: Han detection drives CJK bigram emission, Arabic detection drives the Urdu
// orthography fold, and Latin detection decides whether a combining mark is decoration to strip
// or a Devanagari matra to keep. Hand-writing those ranges from memory is exactly the kind of
// silent, wrong-answers-with-no-exception failure this port has to avoid, so they are generated.
//
// Run with the same JDK the Android unit tests run on - Gradle uses Android Studio's JBR, so
// Unicode data matches what produced the corpus expectations:
//
//   "C:\Program Files\Android\Android Studio\jbr\bin\java.exe" DumpUnicodeScripts.java > out.cs
//
// Only the BMP is emitted. Kotlin's Tokenizer passes Char.code, which is a UTF-16 code unit, so
// a supplementary character arrives as two surrogates and never as its real code point. Java maps
// surrogates to UNKNOWN; reproducing that is deliberate. "Fixing" it by combining pairs would
// change tokenization and diverge from the index Android built.

import java.lang.Character.UnicodeScript;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;

public class DumpUnicodeScripts {

    record Range(int start, int end, String script) {}

    public static void main(String[] args) {
        List<Range> ranges = new ArrayList<>();
        String current = scriptOf(0);
        int start = 0;

        for (int cp = 1; cp <= 0xFFFF; cp++) {
            String s = scriptOf(cp);
            if (!s.equals(current)) {
                ranges.add(new Range(start, cp - 1, current));
                current = s;
                start = cp;
            }
        }
        ranges.add(new Range(start, 0xFFFF, current));

        // UNKNOWN is the default, so those ranges need not be stored.
        List<Range> kept = ranges.stream().filter(r -> !r.script().equals("UNKNOWN")).toList();

        LinkedHashSet<String> scripts = new LinkedHashSet<>();
        scripts.add("UNKNOWN");
        for (Range r : kept) scripts.add(r.script());

        StringBuilder sb = new StringBuilder();
        sb.append("// <auto-generated/>\n");
        sb.append("// Generated by tools/port/DumpUnicodeScripts.java from JDK ")
          .append(System.getProperty("java.version")).append(".\n");
        sb.append("// Do not edit by hand - regenerate if the engine ever needs a script not listed.\n");
        sb.append("//\n");
        sb.append("// BMP only, and surrogates are UNKNOWN, because Kotlin's Tokenizer passes a UTF-16\n");
        sb.append("// code unit rather than a code point. See the generator for why that is preserved.\n");
        sb.append("\nnamespace Atomic.Core.Text;\n\n");

        sb.append("public enum UnicodeScript\n{\n");
        for (String s : scripts) sb.append("    ").append(pascal(s)).append(",\n");
        sb.append("}\n\n");

        sb.append("public static partial class UnicodeScripts\n{\n");
        sb.append("    // start, end, script - ordered, non-overlapping, binary searched.\n");
        sb.append("    private static readonly (char Start, char End, UnicodeScript Script)[] Ranges =\n    [\n");
        for (Range r : kept) {
            sb.append(String.format("        ('\\u%04X', '\\u%04X', UnicodeScript.%s),%n",
                    r.start(), r.end(), pascal(r.script())));
        }
        sb.append("    ];\n}\n");

        System.out.print(sb);
        System.err.printf("%d ranges, %d scripts%n", kept.size(), scripts.size());
    }

    private static String scriptOf(int cp) {
        if (Character.isSurrogate((char) cp)) return "UNKNOWN";
        try {
            return UnicodeScript.of(cp).name();
        } catch (IllegalArgumentException e) {
            return "UNKNOWN";
        }
    }

    private static String pascal(String screamingSnake) {
        StringBuilder out = new StringBuilder();
        for (String part : screamingSnake.split("_")) {
            if (part.isEmpty()) continue;
            out.append(Character.toUpperCase(part.charAt(0)))
               .append(part.substring(1).toLowerCase());
        }
        return out.toString();
    }
}
