#!/usr/bin/env python3
"""
Generate Lexicon.g.cs from Android's nlu/Lexicon.kt.

The lexicon is the operator vocabulary the planner recognises across twelve languages: 71
declarations, ~5,000 surface forms, no logic. It stays **generated C# source**, not an embedded
JSON resource, and that is a deliberate choice:

Its entries are diacritic-folded lowercased forms that must match whatever Tokenizer.Normalize
emits - "storre an", not "större än". A JSON file that *looks* editable invites someone to "fix"
the spelling, and the moment they do, Swedish comparators stop matching with no error anywhere.
Generated source with an <auto-generated/> banner says what it is.

Re-runnable, like every other converter here: this is the mechanism for pulling future Android
vocabulary changes across, not a one-off.

Lookup sets are FrozenSet/FrozenDictionary. Membership is tested per token per clause, several
times per query, and both are in-box on net8.0.

Usage:
    python kt2cs_lexicon.py            # report
    python kt2cs_lexicon.py --write
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys
import unicodedata

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from kt2cs_model import KotlinScanner, kotlin_string_to_csharp  # noqa: E402

HERE = pathlib.Path(__file__).resolve()
WIN_REPO = HERE.parents[2]
SOURCE = WIN_REPO.parents[1] / "Atomic-Periodic-Table.Android" / "app" / "src" / "main" / \
    "java" / "com" / "jlindemann" / "science" / "ai" / "nlu" / "Lexicon.kt"
OUT = WIN_REPO / "src" / "Atomic.Core" / "Ai" / "Nlu" / "Lexicon.g.cs"

# Kotlin enum member -> the C# member. The C# enums are PascalCase where Kotlin is SCREAMING_CASE,
# so the mapping is mechanical, but it is written out rather than derived: a silent mis-mapping
# here would put an element in the wrong series with nothing to catch it.
ENUM_RENAMES = {
    "SeriesId": {
        "ALKALI_METAL": "AlkaliMetal", "ALKALINE_EARTH_METAL": "AlkalineEarthMetal",
        "TRANSITION_METAL": "TransitionMetal", "POST_TRANSITION_METAL": "PostTransitionMetal",
        "METALLOID": "Metalloid", "REACTIVE_NONMETAL": "ReactiveNonmetal",
        "OTHER_NONMETAL": "OtherNonmetal", "NOBLE_GAS": "NobleGas", "HALOGEN": "Halogen",
        "LANTHANOID": "Lanthanoid", "ACTINIDE": "Actinide", "UNKNOWN": "Unknown",
    },
    "Block": {"S": "S", "P": "P", "D": "D", "F": "F", "UNKNOWN": "Unknown"},
    "FieldCategory": {},  # filled from the C# enum below
}

# Kotlin declared type -> (C# type, how to build it).
#
# Lists stay ordered: several are scanned longest-first, and OperatorExtractor relies on the
# authoring order for tie-breaks. Only the genuinely unordered ones become sets.
LIST_TYPE = "IReadOnlyList<string>"
SET_TYPE = "FrozenSet<string>"


def csharp_enum_members(enum_name: str) -> dict[str, str]:
    """Read a C# enum's members so the SCREAMING_CASE mapping can be checked, not assumed."""
    for path in (WIN_REPO / "src" / "Atomic.Core" / "Ai" / "Data").glob("*.cs"):
        text = path.read_text(encoding="utf-8")
        match = re.search(rf"enum {enum_name}\s*\{{(.*?)^\s*\}}", text, re.S | re.M)
        if match:
            # Members may share a line ("Identity, Thermo, Atomic,"), so split on commas rather
            # than anchoring to the line start; doc comments are removed first.
            body = re.sub(r"///.*?$|/\*.*?\*/", "", match.group(1), flags=re.S | re.M)
            members = [m.strip().split("=")[0].strip() for m in body.split(",")]
            members = [m for m in members if re.fullmatch(r"[A-Z][A-Za-z0-9]*", m)]
            return {m.upper(): m for m in members}
    return {}


def screaming_to_pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def strip_comments(text: str) -> str:
    """
    Blank out // and /* */ comments, preserving every offset.

    Offsets have to survive because the declaration regex and the paren scanner both index into
    the original text. Blanking rather than deleting also means a comment can hold a quote - and
    several do, quoting the very query that used to fail - without derailing the string scanner.
    """
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '"':
            scanner = KotlinScanner(text)
            scanner.i = i
            try:
                scanner.skip_string()
                i = scanner.i
            except ValueError:
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            while i < n and not (text[i] == "*" and i + 1 < n and text[i + 1] == "/"):
                if text[i] != "\n":
                    out[i] = " "
                i += 1
            for _ in range(min(2, n - i)):
                out[i] = " "
                i += 1
            continue
        i += 1
    return "".join(out)


# A trailing line comment, captured so the language tags survive into the generated file. Knowing
# which block of surface forms is Swedish and which is Urdu is most of what makes this file
# reviewable at all.
TRAILING_COMMENT = re.compile(r"//\s*(.*?)\s*$")


class Declaration:
    def __init__(self, name: str, kotlin_type: str | None, kind: str, body: str):
        self.name = name
        self.kotlin_type = kotlin_type
        self.kind = kind          # listOf | mapOf | setOf
        self.body = body


DECL = re.compile(
    r"^\s+(?:@JvmField\s+)?(?:private\s+)?val\s+([A-Za-z_][A-Za-z0-9_]*)\s*"
    r"(?::\s*([^=]+?))?\s*=\s*(listOf|mapOf|setOf)\s*\(",
    re.M)


def parse(text: str) -> list[Declaration]:
    """
    Parse from a comment-blanked copy, but slice the *original* for the body, so the language
    tags are still there to re-emit.
    """
    clean = strip_comments(text)
    out: list[Declaration] = []
    for match in DECL.finditer(clean):
        scanner = KotlinScanner(clean)
        scanner.i = match.end() - 1          # sits on the '('
        args = scanner.read_args()
        start, end = match.end(), scanner.i - 1
        out.append(Declaration(
            name=match.group(1),
            kotlin_type=(match.group(2) or "").strip() or None,
            kind=match.group(3),
            body=text[start:end]))
        out[-1].args = args                  # type: ignore[attr-defined]
    return out


def source_lines(decl) -> list[tuple[list[str], str | None]]:
    """
    The declaration's body as (values on that source line, trailing comment).

    Emitting one output line per input line keeps the generated file diffable against Lexicon.kt,
    which is what makes the next vocabulary sync reviewable rather than a wall of churn.
    """
    rows: list[tuple[list[str], str | None]] = []
    pending = ""          # an entry still open across lines, e.g. `"x" to listOf(`
    pending_comments: list[str] = []

    for line in decl.body.splitlines():
        comment_match = TRAILING_COMMENT.search(strip_strings(line))
        comment = None
        if comment_match:
            at = line.rindex("//", comment_match.start())
            comment = line[at + 2:].strip()
            line = line[:at]

        combined = pending + ("\n" if pending else "") + line
        if depth_of(combined) > 0:
            # A value like `"nuclide_table" to listOf(` opens a bracket the next lines close.
            # Accumulate until it balances rather than splitting mid-entry.
            pending = combined
            if comment:
                pending_comments.append(comment)
            continue

        pending = ""
        if comment:
            pending_comments.append(comment)
        values = [v for v in split_top_level(combined) if v.strip()]
        merged = "; ".join(pending_comments) if pending_comments else None
        pending_comments = []
        if values or merged:
            rows.append((values, merged))

    if pending.strip():
        raise ValueError(f"{decl.name}: unbalanced brackets in the declaration body")
    return rows


def depth_of(text: str) -> int:
    """Net bracket depth of a fragment, ignoring brackets inside string literals."""
    scanner = KotlinScanner(text)
    depth = 0
    while scanner.i < len(text):
        c = text[scanner.i]
        if c == '"':
            scanner.skip_string()
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        scanner.i += 1
    return depth


def strip_strings(line: str) -> str:
    """Blank string bodies so a `//` inside a literal is not read as a comment."""
    out, i, n = [], 0, len(line)
    while i < n:
        if line[i] == '"':
            scanner = KotlinScanner(line)
            scanner.i = i
            try:
                scanner.skip_string()
                out.append('"' + " " * (scanner.i - i - 2) + '"')
                i = scanner.i
                continue
            except ValueError:
                pass
        out.append(line[i])
        i += 1
    return "".join(out)


def split_top_level(line: str) -> list[str]:
    """Split one source line on commas that are not inside a string or nested call."""
    parts, depth, start = [], 0, 0
    scanner = KotlinScanner(line)
    while scanner.i < len(line):
        c = line[scanner.i]
        if c == '"':
            scanner.skip_string()
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            parts.append(line[start:scanner.i])
            start = scanner.i + 1
        scanner.i += 1
    parts.append(line[start:])
    return parts


def convert_value(raw: str, enums: dict[str, dict[str, str]]) -> str:
    """One Kotlin expression -> a C# expression."""
    text = raw.strip()

    if text.startswith('"'):
        scanner = KotlinScanner(text)
        value = kotlin_string_to_csharp(scanner.skip_string())
        if scanner.i != len(text):
            raise ValueError(f"trailing text after string: {text!r}")
        return f'"{value}"'

    if re.fullmatch(r"-?\d+", text):
        return text

    if text in ("true", "false"):
        return text

    # setOf(SeriesId.NOBLE_GAS, ...) -> new HashSet<SeriesId> { ... }
    #
    # Not a collection expression: FrozenSet<T> is abstract, so `[x]` cannot target it. HashSet is
    # also what Filter.InSeries takes (IReadOnlySet<SeriesId>), so the values go straight in with
    # no conversion at the call site.
    if text.startswith("setOf("):
        scanner = KotlinScanner(text)
        scanner.i = len("setOf")
        items = [convert_value(i, enums) for i in scanner.read_args()]
        element_type = items[0].split(".")[0] if items else "string"
        return f"new HashSet<{element_type}> {{ " + ", ".join(items) + " }"

    if text.startswith("listOf("):
        scanner = KotlinScanner(text)
        scanner.i = len("listOf")
        items = scanner.read_args()
        return "[" + ", ".join(convert_value(i, enums) for i in items) + "]"

    # A parenthesised Kotlin pair: ("density" to true) -> a C# tuple.
    if text.startswith("("):
        scanner = KotlinScanner(text)
        inner = scanner.read_args()
        if len(inner) == 1 and " to " in inner[0]:
            left, right = split_pair(inner[0])
            return f"({convert_value(left, enums)}, {convert_value(right, enums)})"

    # An enum member, possibly fully qualified.
    member = text.split(".")
    if len(member) >= 2:
        enum_name, value = member[-2], member[-1]
        table = enums.get(enum_name)
        if table is not None:
            renamed = ENUM_RENAMES.get(enum_name, {}).get(value) or table.get(
                value.replace("_", ""), None) or screaming_to_pascal(value)
            if renamed not in table.values():
                raise ValueError(f"{enum_name}.{value} -> {renamed}, which is not a C# member "
                                 f"of {enum_name} ({sorted(table.values())})")
            return f"{enum_name}.{renamed}"

    raise ValueError(f"unhandled value: {text!r}")


PAIR = re.compile(r"^(.*?)\s+to\s+(.*)$", re.S)


def split_pair(entry: str) -> tuple[str, str]:
    """Split `"key" to value` without being fooled by a `to` inside a string literal."""
    scanner = KotlinScanner(entry.strip())
    if scanner.text[scanner.i] != '"':
        raise ValueError(f"map key is not a string literal: {entry!r}")
    scanner.skip_string()
    rest = scanner.text[scanner.i:]
    stripped = rest.lstrip()
    if not stripped.startswith("to "):
        raise ValueError(f"expected 'to' after map key: {entry!r}")
    key = scanner.text[:scanner.i]
    value = stripped[len("to "):]
    return key, value


def value_type(decl, enums) -> str:
    """The C# type of a map's values, read from the Kotlin annotation where there is one."""
    kt = decl.kotlin_type or ""
    # Exactly one '>' - the map's own. rstrip('>') would eat the value type's closing bracket too
    # and turn Set<SeriesId> into Set<SeriesI.
    inner = ""
    if "," in kt:
        inner = kt.split(",", 1)[1].strip()
        if inner.endswith(">"):
            inner = inner[:-1].strip()

    if inner in ("Int",):
        return "int"
    if inner in ("String",):
        return "string"
    if inner.startswith("Set<"):
        # IReadOnlySet, matching what Filter.InSeries takes.
        return f"IReadOnlySet<{inner[4:-1].split('.')[-1]}>"
    if inner.startswith("List<"):
        return f"IReadOnlyList<{inner[5:-1].split('.')[-1].replace('String', 'string')}>"
    if inner.startswith("Pair<"):
        left, right = (p.strip() for p in inner[5:-1].split(","))
        left = "string" if left == "String" else left
        right = "bool" if right == "Boolean" else right
        return f"({left} Field, {right} Ascending)"
    if inner:
        return inner.split(".")[-1]

    # No annotation: infer from the first value.
    _, first = split_pair(decl.args[0])
    converted = convert_value(first, enums)
    if converted.startswith('"'):
        return "string"
    if re.fullmatch(r"-?\d+", converted):
        return "int"
    return converted.split(".")[0]


def emit(decls: list[Declaration], enums) -> str:
    lines = [
        "// <auto-generated/>",
        "// Generated by tools/port/kt2cs_lexicon.py from Android's nlu/Lexicon.kt.",
        "// Do not edit by hand, and do not \"fix\" the spelling.",
        "//",
        "// Every entry is already lowercased and stripped of Latin diacritics, because that is the",
        "// shape Tokenizer.Normalize produces. \"storre an\" is not a typo for \"storre an\" - it is",
        "// what \"storre an\" becomes after folding, and correcting it to the accented spelling",
        "// would stop Swedish comparators matching, silently and with no error anywhere.",
        "",
        "using System.Collections.Frozen;",
        "using System.Collections.Generic;",
        "using Atomic.Core.Ai.Data;",
        "",
        "namespace Atomic.Core.Ai.Nlu;",
        "",
        "/// <summary>",
        "/// The operator vocabulary the planner recognises, across all twelve supported languages.",
        "///",
        "/// <para>These are the words that turn a lookup into a computation - comparators,",
        "/// superlatives, aggregations, counts and subset names. The legacy agent had superlatives in",
        "/// one undifferentiated bag, so it could not tell \"densest\" from \"least dense\" and had to",
        "/// re-test with English Contains checks inside its handler. Here the two directions are",
        "/// separate sets from the start.</para>",
        "/// </summary>",
        "public static class Lexicon",
        "{",
    ]

    for decl in decls:
        rows = source_lines(decl)

        if decl.kind in ("listOf", "setOf"):
            kind = SET_TYPE if decl.kind == "setOf" else LIST_TYPE
            opener = "    [" if decl.kind == "listOf" else \
                     f"    new HashSet<string>(StringComparer.Ordinal)\n    {{"
            closer = "    ];" if decl.kind == "listOf" else \
                     "    }.ToFrozenSet(StringComparer.Ordinal);"
            lines.append(f"    public static readonly {kind} {decl.name} =")
            lines.append(opener)
            for values, comment in rows:
                converted = [convert_value(v, enums) for v in values]
                text = "        " + ", ".join(converted) + ("," if converted else "")
                if comment:
                    text = (text + "  " if converted else "        ") + f"// {comment}"
                lines.append(text.rstrip())
            lines.append(closer)
        else:
            vtype = value_type(decl, enums)
            lines.append(
                f"    public static readonly FrozenDictionary<string, {vtype}> {decl.name} =")
            lines.append(f"        new Dictionary<string, {vtype}>(StringComparer.Ordinal)")
            lines.append("        {")
            for values, comment in rows:
                entries = []
                for entry in values:
                    key, value = split_pair(entry)
                    entries.append(
                        f"[{convert_value(key, enums)}] = {convert_value(value, enums)},")
                text = "            " + " ".join(entries)
                if comment:
                    text = (text + "  " if entries else "            ") + f"// {comment}"
                lines.append(text.rstrip())
            lines.append("        }.ToFrozenDictionary(StringComparer.Ordinal);")

        lines.append("")

    lines.append("}")
    return "\n".join(lines) + "\n"


def chunked(items, size):
    for i in range(0, len(items), size):
        yield items[i:i + size]


def fold(text: str) -> str:
    """
    The same fold TextMatching.NormalizeForLookup applies: lowercase, ss for sharp s, and strip
    combining marks that sit on a Latin letter. Reimplemented here rather than shelled out to,
    because the point is to check the *source* before it reaches C# at all.
    """
    nfd = unicodedata.normalize("NFD", text.lower().replace("ß", "ss"))
    out, base = [], None
    for ch in nfd:
        if unicodedata.category(ch) in ("Mn", "Mc", "Me"):
            if base is None or not (base.isalpha() and ord(base) < 0x0370):
                out.append(ch)
        else:
            base = ch
            out.append(ch)
    return unicodedata.normalize("NFC", "".join(out))


def audit(decls, enums) -> None:
    """
    Report the two things that make an entry silently unreachable.

    Neither is a conversion problem - both are already true in Lexicon.kt - so this reports rather
    than repairs. Preserving them keeps the port faithful; the corpus gate decides whether they
    are worth fixing on both platforms.
    """
    unfolded, collapsed = [], []

    for decl in decls:
        seen: dict[str, str] = {}
        for values, _ in source_lines(decl):
            for value in values:
                key = split_pair(value)[0] if decl.kind == "mapOf" else value
                text = convert_value(key, enums).strip('"')

                if text and fold(text) != text:
                    unfolded.append((decl.name, text, fold(text)))

                if decl.kind != "listOf":
                    mapped = convert_value(split_pair(value)[1], enums) if decl.kind == "mapOf" else ""
                    if text in seen:
                        collapsed.append((decl.name, text, seen[text] == mapped))
                    seen[text] = mapped

    if unfolded:
        print(f"\n{len(unfolded)} entries carry Latin diacritics and can NEVER match - the lexicon "
              f"is compared against text that has already been folded:")
        for name, text, folded in unfolded:
            print(f"    {name:24s} {text!r} would have to be {folded!r}")

    if collapsed:
        conflicting = [c for c in collapsed if not c[2]]
        print(f"\n{len(collapsed)} duplicate key(s) collapse in the maps "
              f"({len(conflicting)} of them to a *different* value):")
        for name, text, same in collapsed:
            print(f"    {name:24s} {text!r}{'' if same else '   <-- CONFLICTING VALUE'}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    if not SOURCE.is_file():
        print(f"Lexicon.kt not found: {SOURCE}")
        return 1

    enums = {name: csharp_enum_members(name) for name in ("SeriesId", "Block", "FieldCategory")}
    missing = [n for n, m in enums.items() if not m]
    if missing:
        print(f"could not read C# enum(s): {', '.join(missing)}")
        return 1

    decls = parse(SOURCE.read_text(encoding="utf-8"))
    if not decls:
        print("no declarations parsed - has Lexicon.kt changed shape?")
        return 1

    try:
        code = emit(decls, enums)
    except ValueError as e:
        print(f"FAILED: {e}")
        return 1

    entries = sum(len(d.args) for d in decls)
    lists = sum(1 for d in decls if d.kind == "listOf")
    maps = sum(1 for d in decls if d.kind == "mapOf")
    sets = sum(1 for d in decls if d.kind == "setOf")
    print(f"{len(decls)} declarations ({lists} lists, {maps} maps, {sets} sets), {entries} entries")

    audit(decls, enums)

    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(code, encoding="utf-8")
        print(f"wrote {OUT.relative_to(WIN_REPO)}")
    else:
        print("\nDRY RUN - nothing written.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
